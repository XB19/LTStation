"""Génère le schéma PostgreSQL de la base locale Station (StationNEW d'origine).

Usage : python station_schema_gen.py [base_sqlserver]
Écrit ../station/schema_tables.sql et ../station/naming.json (ancien nom -> nouveau nom).
Mêmes conversions que schema_gen.py (snake_case, types), avec en plus les index
secondaires de l'original. La table de sauvegarde NormalNoz_Backup_* est ignorée.
"""
import json
import os
import re
import sys

import pyodbc

from schema_gen import pg_default, pg_type, q, snake

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "..", "station")
SRC_DB = sys.argv[1] if len(sys.argv) > 1 else "LTStation_Source_StationNEW_Test"
CONN = (
    "DRIVER={ODBC Driver 18 for SQL Server};SERVER=.\\SQLEXPRESS;"
    f"DATABASE={SRC_DB};Trusted_Connection=yes;TrustServerCertificate=yes"
)
SKIP = re.compile(r"_Backup_\d+$", re.I)


def main():
    cur = pyodbc.connect(CONN).cursor()
    tables = [r[0] for r in cur.execute(
        "SELECT name FROM sys.tables WHERE is_ms_shipped=0 ORDER BY name") if not SKIP.search(r[0])]
    cols = cur.execute("""
        SELECT t.name, c.name, ty.name, c.max_length, c.precision, c.scale,
               c.is_nullable, c.is_identity, OBJECT_DEFINITION(c.default_object_id), c.column_id
        FROM sys.columns c
        JOIN sys.tables t ON t.object_id=c.object_id
        JOIN sys.types ty ON ty.user_type_id=c.user_type_id
        ORDER BY t.name, c.column_id""").fetchall()
    idx = cur.execute("""
        SELECT t.name, i.name, i.is_primary_key, i.is_unique, c.name, ic.key_ordinal, ic.is_descending_key
        FROM sys.indexes i
        JOIN sys.tables t ON t.object_id=i.object_id
        JOIN sys.index_columns ic ON ic.object_id=i.object_id AND ic.index_id=i.index_id
        JOIN sys.columns c ON c.object_id=ic.object_id AND c.column_id=ic.column_id
        WHERE i.type>0 AND ic.is_included_column=0
        ORDER BY t.name, i.name, ic.key_ordinal""").fetchall()

    pk_map, sec = {}, {}
    for t, name, is_pk, uniq, c, _ord, desc in idx:
        if is_pk:
            pk_map.setdefault(t, []).append(c)
        else:
            s = sec.setdefault((t, name), {"unique": uniq, "cols": []})
            s["cols"].append(snake(c) + (" DESC" if desc else ""))

    by_table = {}
    for row in cols:
        by_table.setdefault(row[0], []).append(row)

    naming = {"tables": {}, "columns": {}}
    out = ["-- Schéma PostgreSQL de la base locale Station, généré depuis la base SQL Server",
           f"-- d'origine ({SRC_DB}). Ne pas modifier à la main : relancer",
           "-- database/tools/station_schema_gen.py.", ""]
    for t in tables:
        nt = snake(t)
        naming["tables"][t] = nt
        naming["columns"][t] = {}
        lines = []
        for (_, c, ty, ml, pr, sc, nullable, ident, dflt, _cid) in by_table[t]:
            nc = snake(c)
            naming["columns"][t][c] = nc
            pgt = pg_type(ty, ml, pr, sc)
            parts = [f"    {q(nc)} {pgt}"]
            if ident:
                parts.append("GENERATED BY DEFAULT AS IDENTITY")
            d = pg_default(dflt, pgt)
            if d is not None and not ident:
                parts.append(f"DEFAULT {d}")
            if not nullable:
                parts.append("NOT NULL")
            lines.append(" ".join(parts))
        if t in pk_map:
            lines.append("    PRIMARY KEY (" + ", ".join(q(snake(c)) for c in pk_map[t]) + ")")
        out.append(f"CREATE TABLE {q(nt)} (\n" + ",\n".join(lines) + "\n);\n")

    for (t, name), s in sorted(sec.items()):
        if SKIP.search(t):
            continue
        iname = snake(f"{t}_{name}")[:63]
        out.append(f"CREATE {'UNIQUE ' if s['unique'] else ''}INDEX {q(iname)} ON {q(snake(t))} ("
                   + ", ".join(s["cols"]) + ");")
    out.append("")

    os.makedirs(OUT_DIR, exist_ok=True)
    with open(os.path.join(OUT_DIR, "schema_tables.sql"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    with open(os.path.join(OUT_DIR, "naming.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(naming, f, ensure_ascii=False, indent=1)
    no_pk = [t for t in tables if t not in pk_map]
    print(f"{len(tables)} tables, {len(cols)} colonnes lues, {len(sec)} index secondaires, "
          f"{len(no_pk)} tables sans clé primaire : {', '.join(no_pk)}")


if __name__ == "__main__":
    main()
