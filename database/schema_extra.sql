-- ============================================================================
-- Logiciel Station (version sans matériel : ventes et cartes saisies à la main)
-- ============================================================================

-- Postes de travail de la station (ShiftConfig du logiciel d'origine)
CREATE TABLE IF NOT EXISTS station_shift_config (
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    station_id integer NOT NULL,
    name varchar(20) NOT NULL,
    start_hour integer NOT NULL DEFAULT 0,
    end_hour integer NOT NULL DEFAULT 24,
    PRIMARY KEY (id)
);

-- Postes ouverts / clôturés ; « shift » reprend le numéro AAAAMMJJNN des rapports duty_*
CREATE TABLE IF NOT EXISTS station_duty (
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    station_id integer NOT NULL,
    shift varchar(10) NOT NULL,
    config_id integer,
    open_time timestamp NOT NULL,
    close_time timestamp,
    open_employee_id integer,
    close_employee_id integer,
    status integer NOT NULL DEFAULT 0,
    cash_counted numeric(18,3),
    memo text,
    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS station_duty_one_open ON station_duty (station_id) WHERE status = 0;

-- Rattachement des ventes saisies au poste
ALTER TABLE oil_transactions ADD COLUMN IF NOT EXISTS duty_id integer;

-- Code PIN des cartes (haché) : sans puce, il protège le paiement par numéro de carte
ALTER TABLE customer_card_infos ADD COLUMN IF NOT EXISTS pin_hash text;
ALTER TABLE employee_card_infos ADD COLUMN IF NOT EXISTS pin_hash text;
ALTER TABLE group_card_infos ADD COLUMN IF NOT EXISTS pin_hash text;

-- Postes : intervalle de tolérance en minutes (ShiftConfig.Scope d'origine)
ALTER TABLE station_shift_config ADD COLUMN IF NOT EXISTS scope integer NOT NULL DEFAULT 0;

-- Paramètres d'impression du ticket (StationPrintForm : 6 lignes) et autres réglages de la station
CREATE TABLE IF NOT EXISTS station_settings (
    station_id integer NOT NULL,
    name varchar(40) NOT NULL,
    value text,
    PRIMARY KEY (station_id, name)
);
-- Les postes suivent les horaires configurés : plusieurs postes peuvent rester non clôturés ; un enregistrement par numéro de poste
DROP INDEX IF EXISTS station_duty_one_open;
CREATE UNIQUE INDEX IF NOT EXISTS station_duty_shift ON station_duty (station_id, shift);

-- Profils de droits du logiciel Station (AuthorityMess d'origine : liste de droits 1 à 24 séparés par des virgules)
CREATE TABLE IF NOT EXISTS station_authority (
    id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    station_id integer NOT NULL,
    name varchar(40) NOT NULL,
    content text NOT NULL DEFAULT '',
    PRIMARY KEY (id)
);
