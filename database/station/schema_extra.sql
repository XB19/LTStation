-- Tables propres à LTStation dans la base du logiciel Station (appliquées par station_db.py ;
-- le logiciel les crée aussi au premier usage s'il les trouve absentes : voir sw/core/WorkOrderData.java).

-- Équipements (engins, véhicules, machines) avec leur ordre de travail.
CREATE TABLE IF NOT EXISTS equipment (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL,
    work_order_no varchar(64),
    category varchar(50),
    brand varchar(50),
    model varchar(50),
    serial_no varchar(64),
    fleet_no varchar(30),
    grade_code varchar(10),
    tank_capacity numeric(10,2),
    status smallint NOT NULL DEFAULT 1,
    memo text,
    create_time timestamp NOT NULL DEFAULT now(),
    create_by varchar(50),
    update_time timestamp,
    update_by varchar(50)
);
CREATE INDEX IF NOT EXISTS ix_equipment_work_order ON equipment (work_order_no);
CREATE UNIQUE INDEX IF NOT EXISTS ux_equipment_serial ON equipment (serial_no) WHERE serial_no IS NOT NULL AND serial_no <> '';

-- Ordre de travail d'une carte, avec historique : une période [valid_from, valid_to) par ordre ;
-- valid_to vide = ordre en cours. Les extractions retrouvent l'ordre en vigueur à la date de chaque opération.
CREATE TABLE IF NOT EXISTS card_work_order (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asn varchar(20) NOT NULL,
    work_order_no varchar(64),
    equipment_id integer REFERENCES equipment (id) ON DELETE SET NULL,
    valid_from timestamp NOT NULL DEFAULT now(),
    valid_to timestamp,
    memo text,
    create_time timestamp NOT NULL DEFAULT now(),
    create_by varchar(50)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_card_work_order_current ON card_work_order (asn) WHERE valid_to IS NULL;
CREATE INDEX IF NOT EXISTS ix_card_work_order_asn ON card_work_order (asn, valid_from);
CREATE INDEX IF NOT EXISTS ix_card_work_order_no ON card_work_order (work_order_no);
CREATE INDEX IF NOT EXISTS ix_card_work_order_equipment ON card_work_order (equipment_id);
